/// Prepared research parameters; omitted components use entity defaults.
pub const CompleteCycleScannerParams = struct {
    window: isize = 200,
    min_period: isize = 5,
    max_period: isize = 80,
    smoothing: f64 = 1600.0,
    genuine_threshold: f64 = 49.0,
    phase_cycles: f64 = 2.0,
    top_k: isize = 3,
    peak_distance: isize = 2,
    max_segments: isize = 5,
    bar_component: ?entities.BarComponent = null,
    quote_component: ?entities.QuoteComponent = null,
    trade_component: ?entities.TradeComponent = null,
};
pub const CompleteCycleScannerOutput = enum(u8) { spectrum = 1, genuine_percent = 2, dominant_period = 3, accepted_count = 4 };
/// Arrays in a Snapshot remain valid until the next update, reset or deinit.
/// Entity outputs own their heatmap/polyline buffers. Updates clone state into
/// a reusable scratch arena and commit only after successful calculation.
pub const CompleteCycleScanner = struct {
    allocator: std.mem.Allocator,
    arena: std.heap.ArenaAllocator,
    scratch: std.heap.ArenaAllocator,
    engine: *numerical.Engine,
    p: CompleteCycleScannerParams,
    bar_func: *const fn (entities.Bar) f64,
    quote_func: *const fn (entities.Quote) f64,
    trade_func: *const fn (entities.Trade) f64,
    mnemonic_buf: [256]u8 = undefined,
    mnemonic_len: usize = 0,
    description_buf: [384]u8 = undefined,
    description_len: usize = 0,
    pub fn init(allocator: std.mem.Allocator, p: CompleteCycleScannerParams) !CompleteCycleScanner {
        try validation.integer(allocator, p.window, "window", 6);
        try validation.integer(allocator, p.min_period, "min_period", 3);
        try validation.integer(allocator, p.max_period, "max_period", 3);
        try validation.real(allocator, p.smoothing, "smoothing", 0.0);
        try validation.real(allocator, p.genuine_threshold, "genuine_threshold", 0.0);
        try validation.real(allocator, p.phase_cycles, "phase_cycles", 0.0);
        try validation.integer(allocator, p.top_k, "top_k", 1);
        try validation.integer(allocator, p.peak_distance, "peak_distance", 1);
        try validation.integer(allocator, p.max_segments, "max_segments", 2);
        if (p.min_period > p.max_period) return error.InvalidRange;
        if (p.genuine_threshold > 100 or (p.phase_cycles != 0 and p.phase_cycles < 1)) return error.InvalidPhaseConfig;
        const bc = p.bar_component orelse entities.bar_component.default_bar_component;
        const qc = p.quote_component orelse entities.quote_component.default_quote_component;
        const tc = p.trade_component orelse entities.trade_component.default_trade_component;
        var suffix_buf: [128]u8 = undefined;
        const suffix = indicators.componentTripleMnemonic(&suffix_buf, bc, qc, tc);
        var arena = std.heap.ArenaAllocator.init(allocator);
        errdefer arena.deinit();
        const a = arena.allocator();
        const engine = try memory.create(a, numerical.Engine{ .p = try memory.clone(a, p) });
        try engine.reset(a);
        var self = CompleteCycleScanner{ .allocator = allocator, .arena = arena, .scratch = std.heap.ArenaAllocator.init(allocator), .engine = engine, .p = p, .bar_func = entities.bar_component.componentValue(bc), .quote_func = entities.quote_component.componentValue(qc), .trade_func = entities.trade_component.componentValue(tc) };
        const mnemonic = try std.fmt.bufPrint(&self.mnemonic_buf, "cscan({d},{d},{d},{d},{d},{d},{d},{d},{d}{s})", .{ p.window, p.min_period, p.max_period, p.smoothing, p.genuine_threshold, p.phase_cycles, p.top_k, p.peak_distance, p.max_segments, suffix });
        self.mnemonic_len = mnemonic.len;
        const description = try std.fmt.bufPrint(&self.description_buf, "Complete cycle scanner {s}", .{mnemonic});
        self.description_len = description.len;
        return self;
    }
    pub fn deinit(self: *CompleteCycleScanner) void {
        self.arena.deinit();
        self.scratch.deinit();
    }
    pub fn reset(self: *CompleteCycleScanner) !void {
        _ = self.scratch.reset(.retain_capacity);
        const a = self.scratch.allocator();
        const engine = try memory.create(a, numerical.Engine{ .p = try memory.clone(a, self.engine.p) });
        try engine.reset(a);
        std.mem.swap(std.heap.ArenaAllocator, &self.arena, &self.scratch);
        self.engine = engine;
    }
    pub fn isPrimed(self: *const CompleteCycleScanner) bool {
        return self.engine.primed(self.allocator) catch false;
    }
    pub fn warmupBars(self: *const CompleteCycleScanner) isize {
        return self.engine.warmup(self.allocator) catch unreachable;
    }
    pub fn update(self: *CompleteCycleScanner, price: f64) !Snapshot {
        _ = self.scratch.reset(.retain_capacity);
        const a = self.scratch.allocator();
        const engine = try memory.clone(a, self.engine);
        const output = try engine.update(a, price);
        std.mem.swap(std.heap.ArenaAllocator, &self.arena, &self.scratch);
        self.engine = engine;
        return output;
    }
    pub fn getMetadata(self: *const CompleteCycleScanner, out: *indicators.Metadata) void {
        const mnemonic = self.mnemonic_buf[0..self.mnemonic_len];
        const description = self.description_buf[0..self.description_len];
        var mnemonic_text: [4][320]u8 = undefined;
        var description_text: [4][448]u8 = undefined;
        var texts: [4]indicators.OutputText = undefined;
        texts[0] = .{ .mnemonic = std.fmt.bufPrint(&mnemonic_text[0], "{s} spectrum", .{mnemonic}) catch unreachable, .description = std.fmt.bufPrint(&description_text[0], "{s} spectrum", .{description}) catch unreachable };
        texts[1] = .{ .mnemonic = std.fmt.bufPrint(&mnemonic_text[1], "{s} genuine_percent", .{mnemonic}) catch unreachable, .description = std.fmt.bufPrint(&description_text[1], "{s} genuine_percent", .{description}) catch unreachable };
        texts[2] = .{ .mnemonic = std.fmt.bufPrint(&mnemonic_text[2], "{s} dominant_period", .{mnemonic}) catch unreachable, .description = std.fmt.bufPrint(&description_text[2], "{s} dominant_period", .{description}) catch unreachable };
        texts[3] = .{ .mnemonic = std.fmt.bufPrint(&mnemonic_text[3], "{s} accepted_count", .{mnemonic}) catch unreachable, .description = std.fmt.bufPrint(&description_text[3], "{s} accepted_count", .{description}) catch unreachable };
        indicators.buildMetadata(out, .complete_cycle_scanner, mnemonic, description, &texts);
    }
    fn wrap(self: *const CompleteCycleScanner, time: i64, result: Snapshot) indicators.OutputArray {
        var output = indicators.OutputArray{};
        output.append(.{ .heatmap = indicators.Heatmap.new(time, @floatFromInt(self.p.min_period), @floatFromInt(self.p.max_period), 1.0, std.math.nan(f64), std.math.nan(f64), result.spectrum) });
        output.append(.{ .heatmap = indicators.Heatmap.new(time, @floatFromInt(self.p.min_period), @floatFromInt(self.p.max_period), 1.0, std.math.nan(f64), std.math.nan(f64), result.genuine_percent) });
        output.append(.{ .scalar = .{ .time = time, .value = result.dominant_period } });
        output.append(.{ .scalar = .{ .time = time, .value = result.accepted_count } });
        return output;
    }
    pub fn updateScalar(self: *CompleteCycleScanner, sample: *const entities.Scalar) indicators.OutputArray {
        const result = self.update(sample.value) catch @panic("invalid observation or allocation failure");
        return self.wrap(sample.time, result);
    }
    pub fn updateBar(self: *CompleteCycleScanner, sample: *const entities.Bar) indicators.OutputArray {
        const result = self.update(self.bar_func(sample.*)) catch @panic("invalid observation or allocation failure");
        return self.wrap(sample.time, result);
    }
    pub fn updateQuote(self: *CompleteCycleScanner, sample: *const entities.Quote) indicators.OutputArray {
        const result = self.update(self.quote_func(sample.*)) catch @panic("invalid observation or allocation failure");
        return self.wrap(sample.time, result);
    }
    pub fn updateTrade(self: *CompleteCycleScanner, sample: *const entities.Trade) indicators.OutputArray {
        const result = self.update(self.trade_func(sample.*)) catch @panic("invalid observation or allocation failure");
        return self.wrap(sample.time, result);
    }
    pub fn indicator(self: *CompleteCycleScanner) indicators.Indicator {
        return .{ .ptr = self, .vtable = &vtable };
    }
    const vtable = indicators.Indicator.GenVTable(CompleteCycleScanner);
};
